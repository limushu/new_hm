import { test, expect } from '@playwright/test';
import { selectOption } from './fields';
test.use({ viewport: { width: 390, height: 844 } });
async function open(page: import('@playwright/test').Page) {
  await page.goto('/?preview=1');
  await page.getByRole('button', { name: '案件', exact: true }).click();
  await page.locator('.case-card').first().click();
}
test('属性名称、类型、内容一次保存，关闭和取消保留原值，关闭按钮不抢初始焦点', async ({ page }) => {
  await open(page);
  await page.locator('.case-focus-main').click();
  const details = page.getByRole('dialog', { name: '节点详情', exact: true });
  await details.getByRole('button', { name: '添加属性', exact: true }).click();
  let editor = page.getByRole('dialog', { name: '添加属性', exact: true });
  await expect(editor.getByRole('button', { name: '关闭', exact: true })).not.toBeFocused();
  await editor.getByLabel('属性名称', { exact: true }).fill('开始');
  await editor.getByLabel('属性值', { exact: true }).fill('本周开始');
  await editor.getByRole('heading').click();
  await expect(details.locator('.object-property-row')).toHaveCount(0);
  await editor.getByRole('button', { name: '取消', exact: true }).click();
  await expect(details.locator('.object-property-row')).toHaveCount(0);
  await details.getByRole('button', { name: '添加属性', exact: true }).click();
  editor = page.getByRole('dialog', { name: '添加属性', exact: true });
  await editor.getByLabel('属性名称', { exact: true }).fill('审理结果');
  await selectOption(page, editor.getByLabel('属性类型', { exact: true }), 'select');
  await editor.getByLabel('属性选项', { exact: true }).fill('待宣判，部分支持，调解');
  await selectOption(page, editor.getByLabel('属性值', { exact: true }), { label: '部分支持' });
  await editor.getByRole('button', { name: '保存属性', exact: true }).click();
  await expect(details.locator('.object-property-row')).toContainText('部分支持');
  await details.getByRole('button', { name: '编辑属性 审理结果', exact: true }).click();
  editor = page.getByRole('dialog', { name: '编辑属性', exact: true });
  await editor.getByLabel('属性名称', { exact: true }).fill('不应保存');
  await editor.getByRole('button', { name: '关闭', exact: true }).click();
  await expect(details.locator('.object-property-row')).toContainText('审理结果');
  await expect(details).not.toContainText('不应保存');
});
test('先选对象类型再选择关联对象，取消不产生关系', async ({ page }) => {
  await open(page);
  await page.locator('.case-focus-main').click();
  const details = page.getByRole('dialog', { name: '节点详情', exact: true });
  const before = await details.locator('.resource-related-object').count();
  await details.getByRole('button', { name: '添加关联', exact: true }).click();
  let editor = page.getByRole('dialog', { name: '添加案件关联', exact: true });
  await expect(editor).toContainText('当前案件');
  await expect(editor.getByLabel('搜索关联对象', { exact: true })).toHaveCount(0);
  await selectOption(page, editor.getByLabel('关联对象类型', { exact: true }), 'task');
  await editor.getByRole('checkbox', { name: /选择 核对当事人提供的材料/ }).check();
  await editor.getByRole('button', { name: '取消', exact: true }).click();
  await expect(details.locator('.resource-related-object')).toHaveCount(before);
  await details.getByRole('button', { name: '添加关联', exact: true }).click();
  editor = page.getByRole('dialog', { name: '添加案件关联', exact: true });
  await selectOption(page, editor.getByLabel('关联对象类型', { exact: true }), 'task');
  await editor.getByRole('checkbox', { name: /选择 核对当事人提供的材料/ }).check();
  await editor.getByRole('button', { name: '保存关联', exact: true }).click();
  await expect(details.locator('.resource-related-object')).toHaveCount(before + 1);
});
test('案件名称失焦不保存，离开前明确选择保存或放弃', async ({ page }) => {
  await open(page);
  const field = page.getByLabel('案件名称', { exact: true });
  const original = await field.inputValue();
  await field.fill('未确认的名称');
  await field.press('Tab');
  await expect(page.locator('.save-state')).toHaveText('名称待保存');
  await page.getByRole('button', { name: '返回看板', exact: true }).click();
  const leaving = page.getByRole('dialog', { name: '离开前保存修改？', exact: true });
  await leaving.getByRole('button', { name: '放弃修改并离开', exact: true }).click();
  await expect(page.locator('.case-card')).toContainText(original);
  await page.locator('.case-card').first().click();
  await field.fill('明确保存的案件名称');
  await page.getByRole('button', { name: '保存名称', exact: true }).click();
  await page.getByRole('button', { name: '返回看板', exact: true }).click();
  await expect(page.locator('.case-card')).toContainText('明确保存的案件名称');
});
